def test_pending_accept_and_discard():
    s = _store()
    s.add_obstacle(0, [(1, 1), (2, 1), (2, 2)], 'dig', core.SOURCE_DIG, pending=True)
    pid = s.areas[0].obstacles[-1].id
    assert s.discard_pending(pid)
    assert not s.discard_pending(pid)
    s.add_obstacle(0, [(1, 1), (2, 1), (2, 2)], 'dig', core.SOURCE_DIG, pending=True)
    pid = s.areas[0].obstacles[-1].id
    assert s.accept_pending(pid, 'hole') == 0
    assert s.areas[0].obstacles[-1].name == 'hole' and not s.areas[0].obstacles[-1].pending
    assert s.accept_pending(pid) is None


