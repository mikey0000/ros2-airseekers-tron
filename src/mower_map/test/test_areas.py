    doc = _vendor_doc()
    for feat in doc['features']:
        t = feat['properties']['type']
        if t == 6:
            feat['geometry']['coordinates'] = [1.0, 1.0]
        if t == 7:
            feat['geometry']['coordinates'] = [1.0, 2.0]
        if t == 5:
            feat['geometry']['coordinates'] = [[[1.0, 1.5], [0.5, 1.5], [0.5, 0.5]]]
