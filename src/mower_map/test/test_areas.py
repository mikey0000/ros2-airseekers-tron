def _cell(spec, mask, x, y):
    r, c = spec.index_of(x, y)
    return int(mask[r, c])


def test_keepout_mask_values():
    s = _store()
    s.add_area('nav', [(10.0, 4.0), (14.0, 4.0), (14.0, 6.0), (10.0, 6.0)], True)
    dock = core.DockPose(13.0, 5.0, 0.0, [(0.2, 0.3), (0.2, -0.3), (-0.2, -0.3), (-0.2, 0.3)])
    spec = core.grid_for_polygons([a.polygon for a in s.areas], 0.1, 2.0)
    mask = core.build_keepout_mask(s.areas, spec, dock.outline_in_map())
    assert mask.dtype == np.int8 and mask.shape == (spec.height, spec.width)
    assert _cell(spec, mask, 2.0, 2.0) == 0        # mowing area
    assert _cell(spec, mask, 5.0, 5.0) == 100      # obstacle
    assert _cell(spec, mask, 11.0, 5.0) == 0       # navigation area
    assert _cell(spec, mask, 13.0, 5.0) == 100     # dock outline
    assert _cell(spec, mask, -1.0, -1.0) == 100    # outside everything
    assert _cell(spec, mask, 12.0, 8.0) == 100


