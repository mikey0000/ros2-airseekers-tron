def test_parser_tolerates_legacy_and_bad_entries():
    text = ('# comment\nno colon here\ndock_x: 5\ndock_qw: 1\narea_count: 3\n'
            'area_0_name: a: with colon\narea_0_polygon: 0,0;1,0;1,1\n'
            'area_0_obstacle_count: 3\n'
            'area_0_obstacle_0: 0.1,0.1;0.2,0.1;0.2,0.2\n'
            'area_0_obstacle_1: 0.1,0.1;0.2,0.1;0.2,0.2\n'
            'area_0_obstacle_2: 0,0;1,1\n'
            'area_1_name: degenerate\narea_1_polygon: 0,0;1,1\n'
            'area_2_name: c\narea_2_polygon: 0,0;2,0;garbage;2,2\n')
    areas, datum = core.parse_areas_dat(text)
    assert datum is None
    assert [a.name for a in areas] == ['a: with colon', 'c']
    assert len(areas[0].obstacles) == 1          # dup + short dropped
    assert len(areas[1].polygon) == 3            # garbage point skipped


def test_dock_yaml_round_trip(tmp_path):
    d = core.DockPose(1.5, -2.25, 0.5, [(0.2, 0.275), (0.2, -0.275), (-0.2, -0.275)])
