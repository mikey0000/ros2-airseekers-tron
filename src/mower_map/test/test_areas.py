def _vendor_doc():
    ring = [[0.8, -1.0, 0.1, 0, 0, 1], [6.0, -1.0, 0, 0, 0, 1], [6.0, 3.0, 0, 0, 0, 1],
            [0.8, 3.0, 0, 0, 0, 1], [0.8, -1.0, 0.1, 0, 0, 1]]
    f = lambda t, geom, coords, **p: {  # noqa: E731
        'type': 'Feature', 'geometry': {'type': geom, 'coordinates': coords},
        'properties': dict(dict(id='id%d_%d' % (t, len(p)), name='', parent_id=0, type=t), **p)}
    return {'type': 'FeatureCollection', 'features': [
        f(3, 'LineString', [[0, 0, 0, 0, 0, 1], [0.8, 0, 0, 0, 0, 1]], name='A'),
        f(1, 'Polygon', [ring], name='A', id='area-a'),
        f(4, 'Polygon', [[[2, 0], [3, 0], [3, 1], [2, 1]]], parent_id='area-a', id='o1'),
        f(4, 'Polygon', [[[4, 0], [5, 0], [5, 1], [4, 1]]], parent_id='', id='o2'),
        f(4, 'Polygon', [[[5.5, 2.5], [7, 2.5], [7, 4], [5.5, 4]]], parent_id='', id='o3'),
        f(4, 'Polygon', [[[20, 20], [21, 20], [21, 21]]], parent_id='', id='o4'),
        f(4, 'Polygon', [[[-0.3, -0.75], [-0.3, 0.75], [1.7, 0.75], [1.7, -0.75]]],
          parent_id='', id='dockzone'),
        f(5, 'Polygon', [[[0.2, 0.275], [0.2, -0.275], [-0.2, -0.275], [-0.2, 0.275]]]),
        f(6, 'Point', [0, 0, 0.1, 0.1, 0], name='charge_point'),
        f(7, 'Point', [0.8, 0], name='undock_point'),
        f(8, 'Point', [0, 0, 0.1, 0.1]),
    ]}


def test_import_vendor_areas_obstacles_dock():
    res = core.import_vendor_geojson(_vendor_doc())
    mow = [a for a in res.areas if not a.is_navigation]
    nav = [a for a in res.areas if a.is_navigation]
    assert len(mow) == 1 and mow[0].name == 'A' and len(mow[0].polygon) == 4
    assert mow[0].polygon[0] == (0.8, -1.0)                  # x,y only
    # o1 by parent_id, o2 by centroid containment, o3 by overlap; o4 and dock zone dropped
    assert len(mow[0].obstacles) == 3
    assert any('outside every area' in w for w in res.warnings)
    assert any('dock no-mow zone' in w for w in res.warnings)
    assert len(nav) == 1 and nav[0].name == 'channel A'
    assert core.point_in_polygon(0.0, 0.0, nav[0].polygon)    # dock covered by the channel
    assert nav[0].channel == [(0.0, 0.0), (0.8, 0.0)]         # centreline kept (re-editable)
    assert nav[0].channel_width_m == pytest.approx(0.7)
    assert (res.dock.x, res.dock.y, res.dock.yaw) == pytest.approx((0, 0, 0))
    assert len(res.dock.outline) == 4


