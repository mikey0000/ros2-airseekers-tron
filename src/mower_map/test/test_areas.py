def test_progress_stamp_and_resize():
    spec = core.grid_for_polygons([SQUARE], 0.1, 0.0)
    g = core.ProgressGrid(spec)
    n = g.stamp_disc(5.0, 5.0, 0.15)
    assert n == int(np.count_nonzero(g.data == 100)) and 4 <= n <= 12
    assert g.stamp_disc(5.0, 5.0, 0.15) == 0           # already stamped
    assert g.stamp_disc(50.0, 50.0, 0.15) == 0         # off-grid is harmless
    bigger = core.grid_for_polygons([SQUARE], 0.1, 3.0)
    g.resize(bigger)
    assert g.data.shape == (bigger.height, bigger.width)
    assert int(np.count_nonzero(g.data == 100)) == n
    r, c = bigger.index_of(5.0, 5.0)
    assert g.data[r, c] == 100
    g.reset()
    assert int(g.data.max()) == 0


