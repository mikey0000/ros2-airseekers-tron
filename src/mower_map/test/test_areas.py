    s = _store()
    s.add_obstacle(0, [(1, 1), (2, 1), (2, 2)], '', core.SOURCE_TRACKER)
    s.add_obstacle(0, [(8, 8), (9, 8), (9, 9)], 'dig', core.SOURCE_DIG, pending=True)
